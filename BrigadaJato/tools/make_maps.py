def deathmatch_extra(rows, spawns):
    """Adiciona spawns livres 'S' nas posicoes (x, y) da metade esquerda."""
    rows = [list((r + "." * W_HALF)[:W_HALF]) for r in rows]
    for x, y in spawns:
        if rows[y][x] == ".":
            rows[y][x] = "S"
    return ["".join(r) for r in rows]


