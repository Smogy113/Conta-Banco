"""Gera os mapas do Brigada Jato em assets/maps/*.txt.

Cada mapa simetrico e descrito pela METADE ESQUERDA (40 colunas) e espelhado.
Ao espelhar: r<->b (spawns de time) e R<->B (bases das bandeiras).

Legenda:
  #  bloco solido          =  plataforma (atravessa por baixo)
  ^  espinhos (dano)       .  vazio
  S  spawn livre (mata-mata / sobrevivencia)
  r  spawn time vermelho   b  spawn time azul
  R  base bandeira verm.   B  base bandeira azul
  a  ponto de bomba A      c  ponto de bomba B
  W  arma                  H  vida
  G  granadas              P  power-up
  T  boneco de treino
"""
import os
import sys

W_HALF = 40
OUT = os.path.join(os.path.dirname(__file__), "..", "assets", "maps")

SWAP = {"r": "b", "b": "r", "R": "B", "B": "R"}


def fix(rows, width):
    out = []
    for i, r in enumerate(rows):
        if len(r) != width:
            print(f"  aviso: linha {i} tem {len(r)} colunas (ajustando para {width})", file=sys.stderr)
        r = (r + "." * width)[:width]
        out.append(r)
    return out


def mirror(rows):
    rows = fix(rows, W_HALF)
    full = []
    for r in rows:
        right = "".join(SWAP.get(ch, ch) for ch in reversed(r))
        full.append(r + right)
    return full


def border(rows):
    h = len(rows)
    w = len(rows[0])
    out = []
    for y, r in enumerate(rows):
        r = list(r)
        if y == 0 or y == h - 1:
            r = ["#"] * w
        r[0] = "#"
        r[-1] = "#"
        out.append("".join(r))
    return out


def save(fid, name_pt, name_en, theme, rows, gravity=None):
    rows = border(rows)
    path = os.path.join(OUT, fid + ".txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"@name {name_pt}\n@name_en {name_en}\n@theme {theme}\n")
        if gravity is not None:
            f.write(f"@gravity {gravity}\n")
        for r in rows:
            f.write(r + "\n")
    print(f"{fid}: {len(rows[0])}x{len(rows)}")
    for r in rows:
        print("   " + r)


